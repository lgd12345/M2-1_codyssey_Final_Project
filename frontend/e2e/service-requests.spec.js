import { test, expect } from '@playwright/test'

async function login(page, loginId) {
  await page.goto('/#/login')
  await page.getByLabel('아이디 또는 이메일', { exact: true }).fill(loginId)
  await page.getByLabel('비밀번호', { exact: true }).fill(process.env.E2E_PASSWORD)
  await page.getByRole('button', { name: '로그인', exact: true }).click()
}

// No route interception or authentication doubles: the test goes through Vite
// preview, FastAPI sessions, server authorization and the disposable PostgreSQL DB.
test('real intake persists, is shared with company/staff and isolated from other companies', async ({ browser, page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await login(page, process.env.E2E_CUSTOMER)
  await expect(page).toHaveURL(/#\/portal$/)
  await expect(page.getByRole('heading', { name: '내 서비스 요청', exact: true })).toBeVisible()
  await expect(page.locator('tbody tr').first()).toBeVisible()  // the list has loaded (other specs may already have filed requests)
  await page.getByRole('link', { name: '새 서비스 요청', exact: true }).click()
  await page.getByRole('combobox', { name: '접수 사유 *', exact: true }).selectOption('공구 교환 이상')
  const picker = page.getByRole('combobox', { name: '기종 *', exact: true })
  await expect(page.getByRole('listbox', { name: '기종 목록', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '기종 목록', exact: true }).click()
  await expect(page.getByRole('listbox', { name: '기종 목록', exact: true }).getByRole('option')).toHaveCount(2)
  await picker.fill('f500')
  await expect(page.getByRole('listbox', { name: '기종 목록', exact: true }).getByRole('option')).toHaveCount(1)
  await expect(page.getByRole('listbox', { name: '기종 목록', exact: true }).getByRole('option')).toHaveText('F500')
  await picker.fill('no-such-model')
  await expect(page.getByRole('status')).toContainText('일치하는 기종이 없습니다.')
  await expect(page.getByRole('button', { name: '전송', exact: true })).toBeDisabled()
  await picker.fill('')
  await expect(page.getByRole('listbox', { name: '기종 목록', exact: true }).getByRole('option')).toHaveCount(2)
  await picker.press('ArrowDown')
  await picker.press('Enter')
  await expect(picker).toHaveValue('F400')
  await expect(page.getByRole('listbox', { name: '기종 목록', exact: true })).toHaveCount(0)
  await page.getByLabel('메시지 *', { exact: true }).fill('ATC 동작 중 정지합니다. 실제 접수 E2E 확인.')
  await expect(page.locator('input[type=file]')).toHaveCount(0)  // attachments are not offered
  await page.context().setOffline(true)
  await page.getByRole('button', { name: '전송', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('서버에 연결하지 못했습니다.')
  await expect(page).toHaveURL(/#\/portal\/new$/)
  await expect(page.getByRole('textbox', { name: '메시지 *' })).toHaveValue('ATC 동작 중 정지합니다. 실제 접수 E2E 확인.')
  await page.context().setOffline(false)
  const response = page.waitForResponse(result => result.url().endsWith('/api/v1/service-requests') && result.request().method() === 'POST')
  await page.getByRole('button', { name: '전송', exact: true }).click()
  const created = await (await response).json()
  expect(created.id).toMatch(/^CLM-\d+$/)
  await expect(page).toHaveURL(new RegExp(`#/portal/${created.id}$`))
  await expect(page.locator('.pd-desc')).toContainText('실제 접수 E2E 확인')
  await page.reload()
  await expect(page.locator('.pd-desc')).toContainText('실제 접수 E2E 확인')
  for (const name of ['정보 추가', '콜백 요청', '종결 요청']) await expect(page.getByRole('button', { name, exact: true })).toHaveCount(0)  // filing is all a customer does
  await page.goto('/#/portal?company=forged-company')
  await expect(page.getByRole('link', { name: created.id, exact: true })).toBeVisible()

  const colleagueContext = await browser.newContext()
  const colleague = await colleagueContext.newPage()
  await login(colleague, process.env.E2E_COLLEAGUE)
  await expect(colleague.getByRole('link', { name: created.id, exact: true })).toBeVisible()
  await colleagueContext.close()

  const otherContext = await browser.newContext()
  const other = await otherContext.newPage()
  await login(other, process.env.E2E_OTHER_CUSTOMER)
  await expect(other.locator('tbody tr').first()).toBeVisible()
  await expect(other.locator('tbody tr', { hasText: created.id })).toHaveCount(0)  // another company never sees it
  const denied = await other.request.get(`/api/v1/service-requests/${created.id}`)
  expect(denied.status()).toBe(404)
  await otherContext.close()

  const staffContext = await browser.newContext()
  const staff = await staffContext.newPage()
  await login(staff, process.env.E2E_STAFF)
  await staff.getByRole('link', { name: created.id, exact: true }).click()
  await expect(staff.getByText('아직 분석 결과가 없습니다.', { exact: false })).toBeVisible()
  await expect(staff.getByRole('button', { name: '나에게 지정', exact: true })).toBeEnabled()
  await staff.getByRole('tab', { name: '권장 부품', exact: true }).click()
  await expect(staff.getByText('아직 분석 결과가 없습니다.', { exact: false })).toBeVisible()
  await expect(staff.locator('.timeline')).toHaveCount(0)
  await expect(staff.getByRole('button', { name: '내부 메모 추가', exact: true })).toBeEnabled()
  const before = await staff.request.get(`/api/v1/service-requests/${created.id}`)
  expect((await before.json()).status).toBe('접수됨')
  await staff.reload()
  await expect(staff.getByRole('heading', { name: created.title, exact: true })).toBeVisible()
  await expect(staff.getByText('아직 분석 결과가 없습니다.', { exact: false })).toBeVisible()

  // Analysis lifecycle through the real UI/API/DB. Only the model call is a controlled server-side double.
  await staff.getByRole('button', { name: 'AI 분석 시작', exact: true }).click()
  await expect(staff.getByText('분석 중입니다.', { exact: false })).toBeVisible()
  await expect(staff.getByText('E2E 통제된 분석 응답', { exact: false })).toBeVisible({ timeout: 15000 })
  await expect(staff.getByText('ATC 암 구동 불량', { exact: false })).toBeVisible()
  await expect(staff.getByRole('button', { name: 'AI 분석 시작', exact: true })).toHaveCount(0)
  await staff.getByRole('tab', { name: '과거 정비 이력', exact: true }).click()
  await expect(staff.getByText('FSR-00001', { exact: false }).first()).toBeVisible()
  await expect(staff.getByRole('checkbox', { name: /서비스/ })).toBeEnabled()
  await expect(staff.getByText('어느 부서에도 전달되지 않았습니다', { exact: false })).toBeVisible()
  const analysed = await (await staff.request.get(`/api/v1/service-requests/${created.id}`)).json()
  expect(analysed.status).toBe('검토 대기')
  expect(analysed.linked).toEqual([])
  await staff.reload()
  await expect(staff.getByText('E2E 통제된 분석 응답', { exact: false })).toBeVisible()
  await staff.goto('/#/cases')
  await expect(staff.locator('tbody tr', { hasText: created.id })).toContainText('검토 대기')
  await staffContext.close()

  // The customer sees only a customer-safe status; no analysis or draft content reaches the browser.
  const afterContext = await browser.newContext()
  const after = await afterContext.newPage()
  await login(after, process.env.E2E_CUSTOMER)
  await expect(after).toHaveURL(/#\/portal$/)
  await after.goto(`/#/portal/${created.id}`)
  await expect(after.locator('.pd-desc')).toContainText('실제 접수 E2E 확인')
  await expect(after.getByText('E2E 통제된 분석 응답', { exact: false })).toHaveCount(0)
  await expect(after.getByText('ATC 점검 방문 초안', { exact: false })).toHaveCount(0)
  const customerView = await (await after.request.get(`/api/v1/service-requests/${created.id}`)).json()
  expect(customerView).not.toHaveProperty('analysis')
  expect(customerView).not.toHaveProperty('departments')
  const denied2 = await after.request.post(`/api/v1/service-requests/${created.id}/analysis`, { headers: { Origin: new URL(after.url()).origin, 'X-CSRF-Token': (await (await after.request.get('/api/v1/auth/me')).json()).csrf_token } })
  expect(denied2.status()).toBe(403)
  await afterContext.close()

  const unassignedContext = await browser.newContext()
  const unassigned = await unassignedContext.newPage()
  await login(unassigned, process.env.E2E_UNASSIGNED)
  await expect(unassigned.getByText('고객사 소속이 등록되지 않았습니다. 관리자에게 문의해 주세요.', { exact: true })).toBeVisible()
  await unassigned.getByRole('link', { name: '새 서비스 요청', exact: true }).click()
  await expect(unassigned.getByRole('combobox', { name: '기종 *', exact: true })).toBeDisabled()
  await expect(unassigned.getByRole('button', { name: '전송', exact: true })).toBeDisabled()
  await unassignedContext.close()
  expect(errors).toEqual([])
})
